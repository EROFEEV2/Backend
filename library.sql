Права доступа. Для создания базы данных и таблиц нужны соответствующие права (например, CREATE DATABASE, CREATE TABLE).
Регистр имён. Если СУБД настроена с учётом регистра, имена объектов должны всегда писаться одинаково (например, OrderData и ORDERDATA — это разные таблицы). Если без учёта — такие имена считаются одним и тем же объектом.
Нормализация. На этапе проектирования стоит стремиться к правильной нормализации базы данных, чтобы избежать избыточности данных и упростить их обработку.
 
